def build(sources, programs):
    rows = deepcopy(REVIEWED)
    for row in rows:
        row['sources'] = [sources[key] for key in row.pop('source_ids')]
        row['scope']['program_keys'] = [p['id'] for p in programs.values()
            if p['university_id'] == row['university_key'] and p['name'] in row['scope']['program_names']]
    return rows
