'use strict';
const {readFileSync}=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const context=vm.createContext({Intl,Date,Error,document:{addEventListener(){}}});
vm.runInContext(readFileSync(require('node:path').join(__dirname,'../static/personal.js'),'utf8'),context);
const evaluate=code=>vm.runInContext(code,context);
assert.equal(evaluate(`calendarInstant('2026-09-21T14:00','Europe/Moscow')`),'2026-09-21T14:00:00+03:00');
assert.equal(evaluate(`calendarInstant('2026-03-29T03:30','Europe/Berlin')`),'2026-03-29T03:30:00+02:00');
assert.equal(evaluate(`calendarInstant('2026-09-08T10:15','Asia/Kathmandu')`),'2026-09-08T10:15:00+05:45');
assert.throws(()=>evaluate(`calendarInstant('2026-03-29T02:30','Europe/Berlin')`));
assert.throws(()=>evaluate(`calendarInstant('2026-10-25T02:30','Europe/Berlin')`));
assert.throws(()=>evaluate(`calendarInstant('2026-02-29T10:00','Europe/Moscow')`));
assert.equal(evaluate(`eventIncludesDate({time_kind:'date_range',start_date:'2026-12-31',end_date:'2027-01-02'},'2027-01-02')`),true);
assert.equal(evaluate(`eventIncludesDate({time_kind:'date_range',start_date:'2026-12-31',end_date:'2027-01-02'},'2027-01-03')`),false);
assert.equal(evaluate(`eventIncludesDate({time_kind:'undated'},'2026-09-08')`),false);
assert.equal(evaluate(`eventIncludesDate({time_kind:'timed',timezone:'Europe/Moscow',starts_at:'2026-09-08T23:30:00+03:00',ends_at:'2026-09-09T00:00:00+03:00'},'2026-09-09')`),false);
assert.equal(evaluate(`localEventDate({timezone:'Asia/Vladivostok',starts_at:'2026-09-08T23:30:00+10:00'})`),'2026-09-08');
console.log('11 calendar date assertions passed');
